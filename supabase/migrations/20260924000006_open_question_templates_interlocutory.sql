-- Three skeletons the library was missing: the interlocutory בקשות.
--
-- THE GAP. The 25 non-general templates from "שלדי כתיבה משפטית" are OPENING
-- documents — כתב תביעה, כתב הגנה, עתירה, ערעור. But of the eight
-- student-facing writing tasks, seven ask for a בקשה filed inside a case that
-- is already running, and only one of those (בקשה לסעד זמני) had a skeleton.
-- The other six fell back to תבנית כללית לבקשה לבית משפט, which is correct but
-- generic — it cannot tell a candidate what a fee-waiver application must
-- prove, or which four conditions an issue-estoppel argument turns on.
--
-- WHERE THE LAW IN THESE COMES FROM. Not from memory: each one is built on the
-- sources the Bar attached to the tasks themselves (open_questions.question ->
-- quotes), so the skeleton cites what the candidate was actually given —
--
--   fees      תקנות בתי המשפט (אגרות), התשס"ז-2007, תקנות 2 ו-14, and the
--             two cumulative conditions the attached case law states: that the
--             proceeding discloses a cause of action, AND inability to pay,
--             examined for the applicant and the first-degree family they
--             depend on.
--   early
--   decision  תקנה 5 לתקסד"א התשע"ט-2018 (the efficiency / no-contradictory-
--             rulings balance) with the attached ruling that a matter should be
--             decided early where no benefit will come of continuing, and that
--             this is not limited to admissions but covers a purely legal
--             dispute needing no factual inquiry.
--
-- Section numbers the sources do not state are left as ] [ blanks, the same way
-- the source document leaves the facts blank. A skeleton that invents a
-- provision is worse than one that asks the candidate to name it.
--
-- NUMBERED 37-39, continuing the printed document. extract-templates.mjs
-- produces 1-36 from the PDF and load-templates.mjs upserts by number, so these
-- three survive a re-extract untouched — they have no page to be re-read from.
--
-- All three are area `civil`: that is where every task needing them sits today.
-- A fee application is equally at home in an administrative proceeding, and if
-- one ever arrives under an administrative subject this row should move to
-- `general` (offered everywhere) rather than be duplicated.

