/**
 * Helper used by the client island to render the bad-answer feedback subtitle.
 * `{LETTER}` placeholder is wrapped in `<strong>` at render-time, so we keep
 * the template here as the literal pre/post pair. */
export function badFeedbackParts(): {
  pre: ReactNode;
  post: ReactNode;
} {
  // Splits "התשובה הנכונה היא <strong>{LETTER}</strong>. פתחו את ניתוח ה-360°
  // כדי להבין בדיוק למה." into the pre/post halves around {LETTER}, so the
  // caller can drop the letter into a real <strong>.
  const [pre, post] = trySectionCopy.feedback.badSubTemplate.split(
    "<strong>{LETTER}</strong>"
  );
  return { pre, post };
}
