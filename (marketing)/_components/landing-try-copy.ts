import type { ReactNode } from "react";

export type ChoiceLetter = "א" | "ב" | "ג" | "ד";

export type Choice = {
  letter: ChoiceLetter;
  text: string;
  /** True for the single correct choice in each question. */
  correct?: boolean;
};

/** The 7 360° pane keys (in display order, matching the design's tab row). */
export type PaneKey =
  | "topic"
  | "explain"
  | "refs"
  | "distractors"
  | "trap"
  | "angles"
  | "summary";

export type UnlockedPane =
  | { kind: "topic"; title: string; body: string }
  | { kind: "explain"; title: string; body: string }
  | { kind: "refs"; title: string; items: readonly string[] };

export type LockedPane = {
  /** Title shown inside the .t360-locked-content blurred body. */
  bodyTitle: string;
  /** Blurred body — either a single paragraph or a per-choice breakdown
   *  with strong-prefixed labels. */
  body:
    | { kind: "paragraph"; text: string }
    | { kind: "paragraphs"; texts: readonly string[] }
    | {
        kind: "distractors";
        rows: readonly { letter: ChoiceLetter; verdict: "נכון" | "שגוי"; body: string }[];
      };
};

export type QuestionCopy = {
  /** Topic crumb shown in the topicbar (visual-start). */
  crumb: string;
  /** Tag pill shown on the visual-end of the topicbar. */
  tag: string;
  /** qtab label (without the prefix number — the number is rendered by JSX). */
  qtabLabel: string;
  stem: string;
  choices: readonly [Choice, Choice, Choice, Choice];
  /** Which letter is correct. Computed from `choices` but stored explicitly
   *  for fast lookup in the feedback string. */
  correctLetter: ChoiceLetter;
  /** Three unlocked panes (in `topic` / `explain` / `refs` order). */
  unlocked: readonly [UnlockedPane, UnlockedPane, UnlockedPane];
  /** Four locked panes (in `distractors` / `trap` / `angles` / `summary` order). */
  locked: {
    distractors: LockedPane;
    trap: LockedPane;
    angles: LockedPane;
    summary: LockedPane;
  };
};

